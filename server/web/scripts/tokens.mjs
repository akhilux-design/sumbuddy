// Turns design/spec/tokens.json and typography.json into tokens.css: one CSS variable per colour token (light values
// on :root, dark values under prefers-color-scheme: dark), one per size token, and one class per text style.
// build.mjs writes the result to dist/tokens.css, so the design export stays the only source of these values.

const WEIGHTS = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800 };

const FAMILIES = {
  'Bricolage Grotesque': '"Bricolage Grotesque", system-ui, sans-serif',
  'DM Sans': '"DM Sans", system-ui, sans-serif',
};

/** `color/bg/canvas` becomes `--color-bg-canvas`, `space/16` becomes `--space-16`. */
export function cssVar(tokenName) {
  return '--' + tokenName.replace(/\//g, '-');
}

/** `Body/M Strong` becomes `type-body-m-strong`. */
export function typeClass(styleName) {
  return 'type-' + styleName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function rem(px) {
  return `${+(px / 16).toFixed(4)}rem`;
}

export function tokensCss(tokens, typography) {
  const light = [];
  const dark = [];
  for (const [name, value] of Object.entries(tokens.color)) {
    if (!/^#[0-9A-Fa-f]{6}$/.test(value.light) || !/^#[0-9A-Fa-f]{6}$/.test(value.dark)) {
      throw new Error(`Colour token ${name} has no light or dark value`);
    }
    light.push(`  ${cssVar(name)}: ${value.light};`);
    dark.push(`    ${cssVar(name)}: ${value.dark};`);
  }
  const sizes = Object.entries(tokens.size).map(([name, value]) => `  ${cssVar(name)}: ${value}px;`);

  const styles = typography.map((t) => {
    const family = FAMILIES[t.fontFamily];
    const weight = WEIGHTS[t.fontStyle];
    if (!family || !weight) throw new Error(`Unknown font in text style ${t.name}`);
    if (t.lineHeight.unit !== 'PIXELS' || t.letterSpacing.unit !== 'PERCENT') {
      throw new Error(`Unexpected units in text style ${t.name}`);
    }
    const lines = [
      `  font-family: ${family};`,
      `  font-weight: ${weight};`,
      `  font-size: ${rem(t.fontSize)};`,
      `  line-height: ${rem(t.lineHeight.value)};`,
      `  letter-spacing: ${+(t.letterSpacing.value / 100).toFixed(4)}em;`,
    ];
    if (t.textCase === 'UPPER') lines.push('  text-transform: uppercase;');
    return `/* ${t.name}: ${t.fontFamily} ${t.fontStyle} ${t.fontSize} / ${t.lineHeight.value} */\n.${typeClass(t.name)} {\n${lines.join('\n')}\n}`;
  });

  return [
    '/* Generated by build.mjs from design/spec/tokens.json and typography.json. Do not edit. */',
    ':root {',
    '  color-scheme: light dark;',
    ...light,
    ...sizes,
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root {',
    ...dark,
    '  }',
    '}',
    '',
    styles.join('\n\n'),
    '',
  ].join('\n');
}

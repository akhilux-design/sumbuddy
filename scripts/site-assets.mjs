// Builds the generated assets of the public website, https://sumbuddy.akhilux.design/ (GitHub Pages serves `main`;
// docs/publishing.md, "Website"). Run from the repository root:
//
//   node scripts/site-assets.mjs                           tokens, fonts, icons and the app icon
//   node scripts/site-assets.mjs --screens build/previews  also the screenshots
//
// Needs `sips` (macOS) for the app icon and, with --screens, `cwebp` (Homebrew: brew install webp).
//
// Writes, under assets/site/:
//   tokens.css   colours per theme, sizes and text styles from design/spec (the same generator as the friends' page,
//                server/web/scripts/tokens.mjs); the primitives as --primitive-* for fixed colours (the phone bezel);
//                and each text style as --font-<style> and --tracking-<style>, for the policy text, which Jekyll
//                renders without classes
//   fonts/       the self-hosted OFL fonts and licence texts of the friends' page (server/web/public/fonts)
//   icons/       the 3D icons the pages use, from design/icons/svg
//   app-icon.png, favicon-32.png, apple-touch-icon.png   from the store icon (fastlane)
//   screens/     <name>-light.webp and <name>-dark.webp, 540 x 1200, from captures made with
//                `design/tools/capture.sh <preview> light|dark` (both themes from the same build, so they match)
// and _includes/site-theme-color.html (the browser bar colour per theme, from color/bg/canvas).
//
// Everything else of the site is hand-written: index.html, _layouts/policy.html, _includes/site-{head,nav,footer}.html,
// assets/site/site.css and assets/site/policy.js.

import { execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tokensCss, typeClass } from '../server/web/scripts/tokens.mjs';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(repo, 'assets', 'site');

/** 3D icons the home and privacy pages draw, by file name in design/icons/svg. */
export const ICONS = [
  'phone_3d', 'search_3d', 'split_3d', 'chart_3d', 'check_circle_3d', 'card_3d', 'heart_3d', 'file_3d',
  'lock_3d', 'receipt_3d', 'user_3d', 'bank_3d', 'repeat_3d', 'box_3d', 'link_3d', 'alert_3d',
];

/** Screenshot name on the site -> preview name in the app (the eight store screenshots, in their order). */
export const SCREENS = {
  'home': 'screen-home',
  'review-payments': 'review-payments',
  'card-bills': 'screen-home-card-bills',
  'card-bill': 'cardbill-view',
  'month': 'screen-month',
  'group': 'group-page-owes-you',
  'family-month': 'family-home-family-month',
  'splitwise': 'screen-splitwise-chosen',
};

const WEIGHTS = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800 };
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;

function primitivesCss(primitives) {
  const lines = Object.entries(primitives).map(([name, value]) => {
    if (!/^#[0-9A-Fa-f]{6}$/.test(value)) throw new Error(`Primitive ${name} is not a hex colour`);
    return `  --primitive-${name.replace(/\//g, '-')}: ${value};`;
  });
  return [':root {', ...lines, '}'].join('\n');
}

/** Each text style as a `font` shorthand and a tracking value, e.g. --font-heading-l and --tracking-heading-l. */
function fontVarsCss(typography) {
  const lines = typography.flatMap((t) => {
    const name = typeClass(t.name).replace(/^type-/, '');
    const weight = WEIGHTS[t.fontStyle];
    if (!weight) throw new Error(`Unknown font style in text style ${t.name}`);
    return [
      `  --font-${name}: ${weight} ${rem(t.fontSize)}/${rem(t.lineHeight.value)} "${t.fontFamily}", system-ui, sans-serif;`,
      `  --tracking-${name}: ${+(t.letterSpacing.value / 100).toFixed(4)}em;`,
    ];
  });
  return [':root {', ...lines, '}'].join('\n');
}

function themeColorInclude(tokens) {
  const canvas = tokens.color['color/bg/canvas'];
  if (!canvas) throw new Error('No color/bg/canvas token');
  return [
    '<!-- Generated by scripts/site-assets.mjs from color/bg/canvas. Do not edit. -->',
    `  <meta name="theme-color" content="${canvas.light}" media="(prefers-color-scheme: light)">`,
    `  <meta name="theme-color" content="${canvas.dark}" media="(prefers-color-scheme: dark)">`,
    '',
  ].join('\n');
}

/** Removes the files of one kind from a folder, so a shorter list does not leave old files to be published. */
async function clean(dir, pattern) {
  if (!existsSync(dir)) return;
  for (const f of await readdir(dir)) if (pattern.test(f)) await rm(join(dir, f));
}

function run(cmd, args) {
  try {
    execFileSync(cmd, args, { stdio: 'pipe' });
  } catch (e) {
    throw new Error(`${cmd} failed (${e.code === 'ENOENT' ? `${cmd} is not installed` : e.message.split('\n')[0]})`);
  }
}

export async function build({ screens } = {}) {
  await mkdir(out, { recursive: true });

  const tokens = JSON.parse(await readFile(join(repo, 'design', 'spec', 'tokens.json'), 'utf8'));
  const typography = JSON.parse(await readFile(join(repo, 'design', 'spec', 'typography.json'), 'utf8'));
  const header = /^\/\* Generated by build\.mjs[^\n]*\*\//;
  const base = tokensCss(tokens, typography);
  if (!header.test(base)) throw new Error('tokens.mjs changed its header line; update scripts/site-assets.mjs');
  const css = base.replace(header, '/* Generated by scripts/site-assets.mjs from design/spec/tokens.json and typography.json. Do not edit. */');
  await writeFile(join(out, 'tokens.css'), [css, primitivesCss(tokens.primitives), fontVarsCss(typography), ''].join('\n'));
  await writeFile(join(repo, '_includes', 'site-theme-color.html'), themeColorInclude(tokens));

  const fontsOut = join(out, 'fonts');
  await mkdir(fontsOut, { recursive: true });
  await clean(fontsOut, /\.(woff2|txt)$/);
  const fonts = join(repo, 'server', 'web', 'public', 'fonts');
  for (const f of await readdir(fonts)) if (/\.(woff2|txt)$/.test(f)) await cp(join(fonts, f), join(fontsOut, f));

  const iconsOut = join(out, 'icons');
  await mkdir(iconsOut, { recursive: true });
  await clean(iconsOut, /\.svg$/);
  for (const icon of ICONS) await cp(join(repo, 'design', 'icons', 'svg', `${icon}.svg`), join(iconsOut, `${icon}.svg`));

  const storeIcon = join(repo, 'fastlane', 'metadata', 'android', 'en-US', 'images', 'icon.png');
  for (const [name, size] of [['app-icon.png', 96], ['favicon-32.png', 32], ['apple-touch-icon.png', 180]]) {
    run('sips', ['-z', String(size), String(size), storeIcon, '--out', join(out, name)]);
  }

  if (screens) {
    const from = resolve(repo, screens);
    const screensOut = join(out, 'screens');
    for (const [preview, theme] of Object.values(SCREENS).flatMap((p) => [[p, 'light'], [p, 'dark']])) {
      const src = join(from, `${preview}.${theme}.png`);
      if (!existsSync(src)) throw new Error(`Missing ${src}: capture it with design/tools/capture.sh ${preview} ${theme}`);
    }
    await mkdir(screensOut, { recursive: true });
    await clean(screensOut, /\.webp$/);
    for (const [name, preview] of Object.entries(SCREENS)) {
      for (const theme of ['light', 'dark']) {
        run('cwebp', ['-quiet', '-q', '78', '-m', '6', '-resize', '540', '1200', join(from, `${preview}.${theme}.png`), '-o', join(screensOut, `${name}-${theme}.webp`)]);
      }
    }
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--screens');
  const screens = i >= 0 ? (args[i + 1] ?? 'build/previews') : undefined;
  build({ screens })
    .then((dir) => console.log(`Wrote ${dir}${screens ? ' (with screenshots)' : ''} and _includes/site-theme-color.html`))
    .catch((e) => { console.error(e.message); process.exit(1); });
}

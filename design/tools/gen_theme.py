#!/usr/bin/env python3
"""Generates app/src/main/kotlin/com/expenses/app/ui/theme/Tokens.kt from design/spec/tokens.json, and the window
colours the system draws before Compose does (cold start): app/src/main/res/values/colors_window.xml (light) and
values-night/colors_window.xml (dark), used by res/values/themes.xml.

Run from the project root after re-exporting the design:
    python3 design/tools/gen_theme.py
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
tokens = json.loads((root / "design/spec/tokens.json").read_text())
out = root / "app/src/main/kotlin/com/expenses/app/ui/theme/Tokens.kt"


def camel(name: str) -> str:
    parts = [p for p in re.split(r"[/\-_ ]+", name) if p]
    if parts and parts[0] == "color":
        parts = parts[1:]
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def kcolor(hexv: str) -> str:
    h = hexv.lstrip("#")
    if len(h) == 6:
        return f"Color(0xFF{h.upper()})"
    return f"Color(0x{h[6:8].upper()}{h[0:6].upper()})"  # #RRGGBBAA -> 0xAARRGGBB


colors = tokens["color"]
names = [camel(n) for n in colors]
lines = [
    "// Generated by design/tools/gen_theme.py from design/spec/tokens.json. Do not edit by hand.",
    "package com.expenses.app.ui.theme",
    "",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    "/** Semantic colours. Names follow the Figma variables: `color/bg/canvas` is [bgCanvas]. */",
    "@Immutable",
    "data class AppColors(",
    "    val isDark: Boolean,",
]
for n, raw in zip(names, colors):
    lines.append(f"    /** `{raw}` */")
    lines.append(f"    val {n}: Color,")
lines.append(")")
lines.append("")
for mode in ("dark", "light"):
    lines.append(f"val {mode.capitalize()}Colors = AppColors(")
    lines.append(f"    isDark = {'true' if mode == 'dark' else 'false'},")
    for n, raw in zip(names, colors):
        lines.append(f"    {n} = {kcolor(colors[raw][mode])},")
    lines.append(")")
    lines.append("")

space = {k: v for k, v in tokens["size"].items() if k.startswith("space/")}
radius = {k: v for k, v in tokens["size"].items() if k.startswith("radius/")}
lines.append("/** Spacing scale (`space/12` is [Space.s12]). */")
lines.append("object Space {")
for k, v in space.items():
    lines.append(f"    val s{k.split('/')[1]} = {int(v) if float(v).is_integer() else v}.dp")
lines.append("}")
lines.append("")
lines.append("/** Corner radii (`radius/lg` is [Radius.lg]). [full] is a pill or circle. */")
lines.append("object Radius {")
for k, v in radius.items():
    nm = k.split("/")[1].replace("2xl", "xxl")
    lines.append(f"    val {nm} = {int(v) if float(v).is_integer() else v}.dp")
lines.append("}")
lines.append("")
out.write_text("\n".join(lines))
print("wrote", out.relative_to(root), "colours:", len(names))

# The window background behind the first frame: color/bg/canvas per theme, so a cold start shows the canvas, not black.
res = root / "app/src/main/res"
for folder, mode in (("values", "light"), ("values-night", "dark")):
    hexv = colors["color/bg/canvas"][mode].lstrip("#").upper()
    xml = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by design/tools/gen_theme.py from design/spec/tokens.json. Do not edit by hand. -->",
        "<resources>",
        f"    <!-- color/bg/canvas ({mode}): the window behind the first frame. -->",
        f'    <color name="window_background">#{hexv}</color>',
        "</resources>",
        "",
    ]
    (res / folder).mkdir(exist_ok=True)
    (res / folder / "colors_window.xml").write_text("\n".join(xml))
    print("wrote", (res / folder / "colors_window.xml").relative_to(root))

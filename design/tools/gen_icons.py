#!/usr/bin/env python3
"""Generates app/src/main/kotlin/com/expenses/app/ui/icons/AppIcon.kt from the drawables
ic_<name>_line.xml and ic_<name>_3d.xml in app/src/main/res/drawable.

Run from the project root after adding or re-exporting icons:
    python3 design/tools/gen_icons.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parents[2]
res = root / "app/src/main/res/drawable"
out = root / "app/src/main/kotlin/com/expenses/app/ui/icons/AppIcon.kt"

line = {m.group(1) for p in res.glob("ic_*_line.xml") if (m := re.fullmatch(r"ic_(.+)_line\.xml", p.name))}
art = {m.group(1) for p in res.glob("ic_*_3d.xml") if (m := re.fullmatch(r"ic_(.+)_3d\.xml", p.name))}
names = sorted(line & art)
missing = sorted(line ^ art)
if missing:
    print("WARNING: icons without both styles:", missing)


def pascal(n: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in n.split("_"))


rows = "\n".join(f"    {pascal(n)}(R.drawable.ic_{n}_line, R.drawable.ic_{n}_3d)," for n in names)
out.write_text(f"""// Generated by design/tools/gen_icons.py from app/src/main/res/drawable. Do not edit by hand.
package com.expenses.app.ui.icons

import androidx.annotation.DrawableRes
import com.expenses.app.R

/**
 * Every icon in the design system. Each has two drawings:
 * [line] is the 24dp outline (white, tinted by the app) and [art] is the 32dp coloured 3D artwork.
 */
enum class AppIcon(@DrawableRes val line: Int, @DrawableRes val art: Int) {{
{rows}
}}
""")
print("wrote", out.relative_to(root), "icons:", len(names))
